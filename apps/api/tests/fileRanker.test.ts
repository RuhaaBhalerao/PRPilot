import { describe, it, expect } from 'vitest';
import {
  isExcludedFile,
  isGeneratedFileContent,
  extractIssueKeywords,
  rankRepositoryFiles,
  detectExternalRepositoryTarget,
  MIN_GROUNDED_SCORE,
  type TreeFileItem,
} from '../src/services/fileRanker.js';
import type { GithubIssue, GithubRepository } from '@prpilot/shared';

const mockIssue: GithubIssue = {
  number: 28000,
  title: 'Bug: race condition in FiberScheduler work loop',
  body: 'Stack trace points to packages/react-reconciler/src/ReactFiberWorkLoop.js line 452. The scheduler drops lanes under concurrent mode.',
  state: 'open',
  htmlUrl: 'https://github.com/facebook/react/issues/28000',
  authorLogin: 'testdev',
  labels: [{ name: 'React Core' }],
  createdAt: '2024-01-01T00:00:00Z',
  updatedAt: '2024-01-02T00:00:00Z',
  closedAt: null,
  isPullRequest: false,
};

const mockRepo: GithubRepository = {
  ownerLogin: 'facebook',
  name: 'react',
  fullName: 'facebook/react',
  description: 'React core repository',
  htmlUrl: 'https://github.com/facebook/react',
  defaultBranch: 'main',
  primaryLanguage: 'JavaScript',
  stars: 220000,
  openIssueCount: 800,
  isArchived: false,
};

describe('FileRanker Service', () => {
  describe('isExcludedFile', () => {
    it('correctly filters out build outputs, dependencies, binaries, and lockfiles', () => {
      expect(isExcludedFile('node_modules/react/index.js')).toBe(true);
      expect(isExcludedFile('dist/bundle.js')).toBe(true);
      expect(isExcludedFile('build/static/app.js')).toBe(true);
      expect(isExcludedFile('vendor/autoload.php')).toBe(true);
      expect(isExcludedFile('.github/workflows/ci.yml')).toBe(true);
      expect(isExcludedFile('package-lock.json')).toBe(true);
      expect(isExcludedFile('pnpm-lock.yaml')).toBe(true);
      expect(isExcludedFile('src/assets/logo.png')).toBe(true);
      expect(isExcludedFile('src/bundle.min.js')).toBe(true);
      expect(isExcludedFile('LICENSE')).toBe(true);
    });

    it('excludes compiler fixtures, test fixtures, and generated files', () => {
      // Compiler fixtures
      expect(
        isExcludedFile(
          'compiler/packages/babel-plugin-react-compiler/src/__tests__/fixtures/code-example.js'
        )
      ).toBe(true);
      expect(isExcludedFile('fixtures/compiler/test-case.js')).toBe(true);
      expect(isExcludedFile('src/__fixtures__/sample.ts')).toBe(true);

      // Generated runtime code strings & instruction sets
      expect(
        isExcludedFile(
          'packages/react-dom-bindings/src/server/fizz-instruction-set/ReactDOMFizzInstructionSetInlineCodeStrings.js'
        )
      ).toBe(true);
      expect(isExcludedFile('src/types/schema.generated.ts')).toBe(true);
      expect(isExcludedFile('src/lib/parser_generated.js')).toBe(true);
    });

    it('excludes DevTools files when the issue does not concern React DevTools', () => {
      // DevTools files should be excluded by default when hasDevToolsContext is false
      expect(
        isExcludedFile(
          'packages/react-devtools-shared/src/devtools/views/Components/Button.js',
          false
        )
      ).toBe(true);
      expect(
        isExcludedFile(
          'packages/react-devtools-shared/src/devtools/views/Components/Button.css',
          false
        )
      ).toBe(true);
      expect(isExcludedFile('packages/react-devtools/src/index.js', false)).toBe(true);

      // But should be retained if issue explicitly discusses DevTools
      expect(
        isExcludedFile(
          'packages/react-devtools-shared/src/devtools/views/Components/Button.js',
          true
        )
      ).toBe(false);
    });

    it('retains real source files and styles', () => {
      expect(isExcludedFile('packages/react-reconciler/src/ReactFiberWorkLoop.js')).toBe(false);
      expect(isExcludedFile('src/components/Scheduler.tsx')).toBe(false);
      expect(isExcludedFile('src/styles/preview.module.css')).toBe(false);
      expect(isExcludedFile('lib/engine.py')).toBe(false);
    });
  });

  describe('isGeneratedFileContent', () => {
    it('detects generated file comments and headers in file content', () => {
      const generatedSnippet = `// This is a generated file. The source files are in react-dom-bindings/src/server/fizz-instruction-set.
// The build script is at scripts/rollup/generate-inline-fizz-runtime.js.
// Run \`yarn generate-inline-fizz-runtime\` to generate.
export const markShellTime = 'requestAnimationFrame(function(){$RT=performance.now()});';`;

      expect(isGeneratedFileContent(generatedSnippet)).toBe(true);
      expect(isGeneratedFileContent('/* @generated by codegen */')).toBe(true);
      expect(isGeneratedFileContent('// DO NOT EDIT THIS FILE DIRECTLY')).toBe(true);
    });

    it('accepts authentic non-generated source files', () => {
      const normalSource = `import React from 'react';
export function PreviewVideo() {
  return <div className="preview-container">Video</div>;
}`;
      expect(isGeneratedFileContent(normalSource)).toBe(false);
    });
  });

  describe('detectExternalRepositoryTarget', () => {
    it('detects when an issue on facebook/react actually concerns the react.dev documentation site', () => {
      const docIssue: GithubIssue = {
        ...mockIssue,
        number: 37933,
        title: 'Bug: Hover highlight in interactive code example overlaps the preview content',
        body: 'On the react.dev documentation homepage, hover highlighting on the interactive video example overlaps the layout.',
      };

      const advisory = detectExternalRepositoryTarget(docIssue, mockRepo);
      expect(advisory).not.toBeNull();
      expect(advisory?.targetRepository).toBe('reactjs/react.dev');
      expect(advisory?.advisoryMessage).toContain('react.dev documentation website');
      expect(advisory?.suggestedAction).toContain('https://github.com/reactjs/react.dev');
    });

    it('regression test: detects documentation site bug facebook/react#27986 and targets reactjs/react.dev', () => {
      const issue27986: GithubIssue = {
        number: 27986,
        title: 'Bug: Found an error on React Documentation Site',
        body: 'React version: Official Documentation site (`https://react.dev/learn/state-a-components-memory`)\n\n## Steps To Reproduce\n1. Go to https://react.dev/learn/state-a-components-memory\n2. Click Next button repeatedly.\n\n## The current behavior\nnext button not disabled or handle the error',
        state: 'closed',
        htmlUrl: 'https://github.com/facebook/react/issues/27986',
        authorLogin: 'docuser',
        labels: [{ name: 'Status: Unconfirmed' }],
        createdAt: '2024-01-18T10:00:00Z',
        updatedAt: '2024-01-18T20:00:00Z',
        closedAt: '2024-01-18T20:21:14Z',
        isPullRequest: false,
      };

      const reactOrgRepo: GithubRepository = {
        ...mockRepo,
        ownerLogin: 'react',
        name: 'react',
        fullName: 'react/react',
      };

      const advisory = detectExternalRepositoryTarget(issue27986, reactOrgRepo);
      expect(advisory).not.toBeNull();
      expect(advisory?.targetRepository).toBe('reactjs/react.dev');
      expect(advisory?.advisoryMessage).toContain('reactjs/react.dev');
      expect(advisory?.suggestedAction).toContain('https://github.com/reactjs/react.dev');
    });

    it('returns null for core React issues that belong in the facebook/react repository', () => {
      const advisory = detectExternalRepositoryTarget(mockIssue, mockRepo);
      expect(advisory).toBeNull();
    });
  });

  describe('extractIssueKeywords', () => {
    it('extracts explicit paths and standalone file names from issue description', () => {
      const extracted = extractIssueKeywords(mockIssue);

      expect(
        extracted.explicitPaths.has('packages/react-reconciler/src/reactfiberworkloop.js')
      ).toBe(true);
      expect(extracted.explicitFiles.has('reactfiberworkloop.js')).toBe(true);
      expect(extracted.titleKeywords.has('fiberscheduler')).toBe(true);
      expect(extracted.titleKeywords.has('scheduler')).toBe(true);
      expect(extracted.bodyKeywords.has('concurrent')).toBe(true);
    });

    it('filters out generic stop words such as code, example, file, and app from keyword scoring', () => {
      const issueWithGenericWords: GithubIssue = {
        ...mockIssue,
        title: 'Bug in example code file of app',
        body: 'The sample code has an issue when running data.',
      };

      const extracted = extractIssueKeywords(issueWithGenericWords);
      expect(extracted.titleKeywords.has('code')).toBe(false);
      expect(extracted.titleKeywords.has('example')).toBe(false);
      expect(extracted.titleKeywords.has('file')).toBe(false);
      expect(extracted.titleKeywords.has('app')).toBe(false);
    });

    it('detects UI and layout context when visual terms are present', () => {
      const uiIssue: GithubIssue = {
        ...mockIssue,
        title: 'Bug: Hover highlight in interactive code example overlaps the preview content',
        body: 'The preview layout has incorrect CSS positioning and z-index.',
      };

      const extracted = extractIssueKeywords(uiIssue);
      expect(extracted.hasUiContext).toBe(true);
      expect(extracted.uiKeywords.has('hover')).toBe(true);
      expect(extracted.uiKeywords.has('highlight')).toBe(true);
      expect(extracted.uiKeywords.has('preview')).toBe(true);
      expect(extracted.uiKeywords.has('positioning')).toBe(true);
    });
  });

  describe('rankRepositoryFiles', () => {
    const mockTree: TreeFileItem[] = [
      { path: 'packages/react-reconciler/src/ReactFiberWorkLoop.js', size: 15000, type: 'blob' },
      { path: 'packages/scheduler/src/Scheduler.js', size: 8000, type: 'blob' },
      { path: 'packages/react/src/React.js', size: 5000, type: 'blob' },
      { path: 'packages/react-dom/src/ReactDOM.js', size: 12000, type: 'blob' },
      { path: 'node_modules/scheduler/index.js', size: 4000, type: 'blob' },
      {
        path: 'packages/react-reconciler/__tests__/ReactFiberWorkLoop-test.js',
        size: 9000,
        type: 'blob',
      },
      { path: 'docs/README.md', size: 2000, type: 'blob' },
      { path: 'scripts/rollup/build.js', size: 250000, type: 'blob' }, // exceeds 100KB limit
    ];

    it('ranks the explicitly referenced file highest', () => {
      const ranked = rankRepositoryFiles(mockTree, mockIssue, mockRepo, { maxResults: 3 });

      expect(ranked).toHaveLength(3);
      expect(ranked[0].path).toBe('packages/react-reconciler/src/ReactFiberWorkLoop.js');
      expect(ranked[0].score).toBeGreaterThan(100);
      expect(ranked[0].reason).toContain('Explicitly referenced path in issue');
    });

    it('ranks relevant UI component and CSS file above compiler fixtures and server files for UI issues', () => {
      const uiDocIssue: GithubIssue = {
        number: 37933,
        title: 'Bug: Hover highlight in interactive code example overlaps the preview content',
        body: 'The preview video layout in the interactive example has broken CSS styling and position overlapping.',
        state: 'open',
        htmlUrl: 'https://github.com/reactjs/react.dev/issues/37933',
        authorLogin: 'testuser',
        labels: [{ name: 'UI' }],
        createdAt: '2024-01-01T00:00:00Z',
        updatedAt: '2024-01-02T00:00:00Z',
        closedAt: null,
        isPullRequest: false,
      };

      const docRepo: GithubRepository = {
        ownerLogin: 'reactjs',
        name: 'react.dev',
        fullName: 'reactjs/react.dev',
        description: 'React docs site',
        htmlUrl: 'https://github.com/reactjs/react.dev',
        defaultBranch: 'main',
        primaryLanguage: 'TypeScript',
        stars: 15000,
        openIssueCount: 50,
        isArchived: false,
      };

      const mixedTree: TreeFileItem[] = [
        // Real UI & CSS files
        {
          path: 'src/components/InteractiveCodeExample/PreviewVideo.tsx',
          size: 4000,
          type: 'blob',
        },
        { path: 'src/styles/preview-highlight.css', size: 2500, type: 'blob' },
        // Compiler test fixture (must be excluded)
        {
          path: 'compiler/packages/babel-plugin-react-compiler/src/__tests__/fixtures/code-example.js',
          size: 1500,
          type: 'blob',
        },
        // Generated runtime strings (must be excluded)
        {
          path: 'packages/react-dom-bindings/src/server/fizz-instruction-set/ReactDOMFizzInstructionSetInlineCodeStrings.js',
          size: 3000,
          type: 'blob',
        },
        // Unrelated server file (must be penalized)
        { path: 'packages/react-server/src/ReactServerStream.js', size: 8000, type: 'blob' },
      ];

      const ranked = rankRepositoryFiles(mixedTree, uiDocIssue, docRepo);

      expect(ranked.length).toBeGreaterThanOrEqual(1);
      const rankedPaths = ranked.map((r) => r.path);

      // 1. Excluded compiler fixture and generated inline code strings must NOT be present
      expect(rankedPaths).not.toContain(
        'compiler/packages/babel-plugin-react-compiler/src/__tests__/fixtures/code-example.js'
      );
      expect(rankedPaths).not.toContain(
        'packages/react-dom-bindings/src/server/fizz-instruction-set/ReactDOMFizzInstructionSetInlineCodeStrings.js'
      );

      // 2. CSS and UI component must rank at the top
      expect(rankedPaths[0]).toMatch(/\.(css|tsx)$/);
      expect(ranked[0].score).toBeGreaterThanOrEqual(MIN_GROUNDED_SCORE);
    });

    it('enforces MIN_GROUNDED_SCORE threshold and returns empty array when no file is sufficiently relevant', () => {
      const irrelevantTree: TreeFileItem[] = [
        { path: 'packages/unrelated-core/src/InternalEngine.js', size: 1000, type: 'blob' },
        { path: 'scripts/jest/config.js', size: 800, type: 'blob' },
      ];

      const vagueIssue: GithubIssue = {
        ...mockIssue,
        title: 'Unexpected glitch happens',
        body: 'Something seems off.',
      };

      const ranked = rankRepositoryFiles(irrelevantTree, vagueIssue, mockRepo);
      // No file meets MIN_GROUNDED_SCORE, so empty array is returned
      expect(ranked).toHaveLength(0);
    });

    it('excludes node_modules and oversized files from ranked results', () => {
      const ranked = rankRepositoryFiles(mockTree, mockIssue, mockRepo, { maxResults: 10 });

      const paths = ranked.map((r) => r.path);
      expect(paths).not.toContain('node_modules/scheduler/index.js');
      expect(paths).not.toContain('scripts/rollup/build.js');
    });

    it('regression test facebook/react#27986: excludes DevTools button files and rejects generic button keyword matching', () => {
      const issue27986: GithubIssue = {
        number: 27986,
        title: 'Bug: Found an error on React Documentation Site',
        body: 'React version: Official Documentation site (`https://react.dev/learn/state-a-components-memory`)\n\n## Steps To Reproduce\n1. Go to https://react.dev/learn/state-a-components-memory\n2. Click Next button repeatedly.\n\n## The current behavior\nnext button not disabled or handle the error',
        state: 'closed',
        htmlUrl: 'https://github.com/facebook/react/issues/27986',
        authorLogin: 'docuser',
        labels: [{ name: 'Status: Unconfirmed' }],
        createdAt: '2024-01-18T10:00:00Z',
        updatedAt: '2024-01-18T20:00:00Z',
        closedAt: '2024-01-18T20:21:14Z',
        isPullRequest: false,
      };

      const treeWithDevTools: TreeFileItem[] = [
        {
          path: 'packages/react-devtools-shared/src/devtools/views/Components/Button.js',
          size: 3200,
          type: 'blob',
        },
        {
          path: 'packages/react-devtools-shared/src/devtools/views/Components/Button.css',
          size: 1500,
          type: 'blob',
        },
        {
          path: 'packages/react-dom-bindings/src/server/fizz-instruction-set/ReactDOMFizzInstructionSetInlineCodeStrings.js',
          size: 4000,
          type: 'blob',
        },
        {
          path: 'packages/react-reconciler/src/ReactFiberWorkLoop.js',
          size: 18000,
          type: 'blob',
        },
      ];

      const ranked = rankRepositoryFiles(treeWithDevTools, issue27986, mockRepo, {
        minRelevanceScore: 60,
      });

      // Neither DevTools button nor generated inline code string should rank
      const rankedPaths = ranked.map((r) => r.path);
      expect(rankedPaths).not.toContain(
        'packages/react-devtools-shared/src/devtools/views/Components/Button.js'
      );
      expect(rankedPaths).not.toContain(
        'packages/react-devtools-shared/src/devtools/views/Components/Button.css'
      );
      expect(rankedPaths).not.toContain(
        'packages/react-dom-bindings/src/server/fizz-instruction-set/ReactDOMFizzInstructionSetInlineCodeStrings.js'
      );
      expect(ranked).toHaveLength(0);
    });

    it('respects configurable minRelevanceScore threshold', () => {
      const candidates: TreeFileItem[] = [
        { path: 'packages/scheduler/src/Scheduler.js', size: 3000, type: 'blob' },
      ];

      // With very high threshold, nothing passes
      const strictRanked = rankRepositoryFiles(candidates, mockIssue, mockRepo, {
        minRelevanceScore: 200,
      });
      expect(strictRanked).toHaveLength(0);

      // With lower threshold, candidate passes
      const lenientRanked = rankRepositoryFiles(candidates, mockIssue, mockRepo, {
        minRelevanceScore: 10,
      });
      expect(lenientRanked.length).toBeGreaterThanOrEqual(1);
    });

    it('distinguishes direct evidence from indirect reference patterns based on component responsibility', () => {
      const layoutIssue: GithubIssue = {
        ...mockIssue,
        title: 'Bug: Header component layout alignment issue',
        body: 'The Header layout is misaligned with the container padding in src/components/Header.tsx.',
      };

      const tree: TreeFileItem[] = [
        { path: 'src/components/Header.tsx', size: 2500, type: 'blob' },
        { path: 'src/styles/theme-colors.css', size: 1200, type: 'blob' },
      ];

      const ranked = rankRepositoryFiles(tree, layoutIssue, mockRepo, { minRelevanceScore: 10 });
      const headerFile = ranked.find((f) => f.path === 'src/components/Header.tsx');
      const cssFile = ranked.find((f) => f.path === 'src/styles/theme-colors.css');

      expect(headerFile?.evidenceRole).toBe('direct_evidence');
      if (cssFile) {
        expect(cssFile.evidenceRole).toBe('indirect_reference');
      }
    });

    it('produces deterministic output with identical input', () => {
      const run1 = rankRepositoryFiles(mockTree, mockIssue, mockRepo);
      const run2 = rankRepositoryFiles(mockTree, mockIssue, mockRepo);

      expect(run1).toEqual(run2);
    });
  });
});
